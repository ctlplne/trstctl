// The deployment KEK and the signer's authorization secret (HELM-O1). When
// the spec names neither Secret, the operator creates each one at its default
// name, once, with 32 random bytes, as the Helm chart does: the KEK only when
// spec.signer.generateKek is true (production supplies its own, so a generated
// KEK is opt-in, as kek.generate is in the chart), the authorization secret
// unless spec.signer.generateAuthSecret is false. A generated Secret carries
// the operator's labels but no owner reference, so deleting the control plane
// leaves it, as the chart's resource-policy keep does: a new KEK would orphan
// every key the old one sealed. It is never rewritten. A Secret that exists,
// generated earlier or provided, is used as it is.
const (
	generatedKeyBytes      = 32
	generatedKeyAnnotation = "trstctl.com/generated-key"
	generatedKeyNote       = "generated by the trstctl operator; kept when the control plane is deleted and never rewritten"
)

type generatedKey struct {
	surface, name, key, component string
	generate                      bool
}

// generateAuthSecret reports whether the operator creates the signer's
// authorization secret when it is missing (the default, as in the chart).
func (s SignerSpec) generateAuthSecret() bool {
	return s.GenerateAuthSecret == nil || *s.GenerateAuthSecret
}

// ensureGeneratedKeys creates the KEK and authorization Secrets the control
// plane's pods mount when they are missing and the spec lets the operator
// generate them. A missing Secret the operator may not generate is left to
// whoever provides it; the pods wait for it, as they would for any Secret.
func (r *Reconciler) ensureGeneratedKeys(ctx context.Context, namespace string, cr controlPlaneObject) (map[string]Action, error) {
	actions := map[string]Action{}
	for _, k := range []generatedKey{
		{surface: "kek", name: signerKekSecret(cr), key: signerKekSecretKey(cr), component: "kek",
			generate: strings.TrimSpace(cr.Spec.Signer.KekSecret) == "" && cr.Spec.Signer.GenerateKek},
		{surface: "signerAuth", name: signerAuthSecret(cr), key: signerAuthSecretKey(cr), component: "signer-auth",
			generate: strings.TrimSpace(cr.Spec.Signer.AuthSecret) == "" && cr.Spec.Signer.generateAuthSecret()},
	} {
		if !k.generate {
			continue
		}
		action, err := r.ensureGeneratedKey(ctx, namespace, cr, k)
		actions[k.surface] = action
		if err != nil {
			return actions, err
		}
	}
	return actions, nil
}

func (r *Reconciler) ensureGeneratedKey(ctx context.Context, namespace string, cr controlPlaneObject, k generatedKey) (Action, error) {
	st, response, err := r.client.do(ctx, http.MethodGet, secretItemPath(namespace, k.name), "", nil)
	secret.Wipe(response)
	if err != nil {
		return ActionNone, err
	}
	switch {
	case st/100 == 2:
		return ActionNone, nil // generated earlier, or provided: never rewritten
	case st != http.StatusNotFound:
		return ActionNone, fmt.Errorf("operator: get Secret %s/%s: status %d", namespace, k.name, st)
	}
	material, err := crypto.RandomBytes(generatedKeyBytes)
	if err != nil {
		return ActionNone, fmt.Errorf("operator: generate %s: %w", k.component, err)
	}
	defer secret.Wipe(material)
	body, err := json.Marshal(map[string]any{
		"apiVersion": "v1", "kind": "Secret", "type": "Opaque",
		"metadata": map[string]any{
			"name": k.name, "namespace": namespace,
			"labels": map[string]any{
				"app.kubernetes.io/name": "trstctl", "app.kubernetes.io/component": k.component,
				managedByLabel: managedByOperator, ownerLabel: cr.Metadata.Name,
			},
			"annotations": map[string]any{generatedKeyAnnotation: generatedKeyNote},
		},
		"data": map[string][]byte{k.key: material},
	})
	defer secret.Wipe(body)
	if err != nil {
		return ActionNone, err
	}
	st, response, err = r.client.do(ctx, http.MethodPost, secretCollectionPath(namespace), "", body)
	secret.Wipe(response)
	if err != nil {
		return ActionCreate, err
	}
	if st == http.StatusConflict {
		return ActionNone, nil // another replica created it first; it is used as it is
	}
	if st/100 != 2 {
		return ActionCreate, fmt.Errorf("operator: create Secret %s/%s: status %d", namespace, k.name, st)
	}
	return ActionCreate, nil
}

// External KMS custody (HELM-O1): with spec.externalKMS.enabled the signer
// wraps its key store through the KMS adapter instead of the deployment KEK,
// as the chart's signerCustodyArgs does. The control plane keeps the KEK for
// secrets either way.
const (
	defaultKMSWrapCommand = "/usr/local/bin/trstctl-kms-wrap"
	defaultKMSTimeout     = "10s"
	kmsWrapMountPath      = "/etc/trstctl/kms-wrap"
)

var externalKMSProviders = map[string]bool{"awskms": true, "gcpkms": true, "azurekv": true, "pkcs11": true}

// externalKMSError refuses an external KMS the signer could not use.
func (s ControlPlaneSpec) externalKMSError() error {
	k := s.ExternalKMS
	if !k.Enabled {
		return nil
	}
	if !externalKMSProviders[strings.TrimSpace(k.Provider)] {
		return fmt.Errorf("operator: spec.externalKMS.provider %q must be awskms, gcpkms, azurekv or pkcs11", k.Provider)
	}
	if strings.TrimSpace(k.KeyRef) == "" {
		return fmt.Errorf("operator: spec.externalKMS.keyRef is required with spec.externalKMS.enabled")
	}
	if c := strings.TrimSpace(k.WrapCommand); c != "" && (!path.IsAbs(c) || strings.ContainsAny(c, " \t\n")) {
		return fmt.Errorf("operator: spec.externalKMS.wrapCommand %q must be one absolute path", c)
	}
	if t := strings.TrimSpace(k.Timeout); t != "" {
		if d, err := time.ParseDuration(t); err != nil || d <= 0 {
			return fmt.Errorf("operator: spec.externalKMS.timeout %q is not a positive duration", t)
		}
	}
	return nil
}

func firstSet(value, fallback string) string {
	if v := strings.TrimSpace(value); v != "" {
		return v
	}
	return fallback
}

// signerCustodyArgs is how the signer seals its key store: the KEK, or the
// external KMS adapter.
func signerCustodyArgs(cr controlPlaneObject) []string {
	k := cr.Spec.ExternalKMS
	if !k.Enabled {
		return []string{"--kek=/etc/trstctl/kek/" + signerKekSecretKey(cr)}
	}
	return []string{
		"--kms-provider=" + strings.TrimSpace(k.Provider),
		"--kms-key-ref=" + strings.TrimSpace(k.KeyRef),
		"--kms-wrap-command=" + firstSet(k.WrapCommand, defaultKMSWrapCommand),
		"--kms-timeout=" + firstSet(k.Timeout, defaultKMSTimeout),
	}
}

// signerCustodyMounts mounts the KEK, or the KMS adapter's configuration.
func signerCustodyMounts(cr controlPlaneObject) []map[string]any {
	k := cr.Spec.ExternalKMS
	if !k.Enabled {
		return []map[string]any{{"name": "kek", "mountPath": "/etc/trstctl/kek", "readOnly": true}}
	}
	if strings.TrimSpace(k.AdapterConfigSecret) == "" {
		return nil
	}
	return []map[string]any{{"name": "kms-wrap", "mountPath": kmsWrapMountPath, "readOnly": true}}
}

// signerCustodyEnv points the shipped adapter at its configuration.
func signerCustodyEnv(cr controlPlaneObject) []map[string]any {
	k := cr.Spec.ExternalKMS
	if !k.Enabled || strings.TrimSpace(k.AdapterConfigSecret) == "" {
		return nil
	}
	return []map[string]any{envValue("TRSTCTL_KMS_WRAP_CONFIG", kmsWrapMountPath+"/config.json")}
}

// kmsWrapVolume is the adapter configuration Secret's volume, when named.
func kmsWrapVolume(cr controlPlaneObject) []map[string]any {
	k := cr.Spec.ExternalKMS
	if !k.Enabled || strings.TrimSpace(k.AdapterConfigSecret) == "" {
		return nil
	}
	return []map[string]any{{"name": "kms-wrap", "secret": map[string]any{"secretName": strings.TrimSpace(k.AdapterConfigSecret), "defaultMode": 288}}}
}
