func secretData(t *testing.T, obj map[string]any, key string) string {
	t.Helper()
	data, _ := obj["data"].(map[string]any)
	value, _ := data[key].(string)
	return value
}

// TestOperatorGeneratesTheKEKAndSignerAuthorizationOnceHELMO1 is HELM-O1:
// with generateKek the operator creates the deployment KEK at its default
// name, and by default the signer's authorization Secret, each with 32 random
// bytes, labeled but not owned (deleting the control plane keeps them), and
// never rewrites either. Without generateKek, or when the spec names its own
// Secrets, it creates none.
func TestOperatorGeneratesTheKEKAndSignerAuthorizationOnceHELMO1(t *testing.T) {
	f := newFakeCluster()
	cr := tcpObjectFullConfig("prod")
	cr["spec"].(map[string]any)["signer"] = map[string]any{"authTokenCommand": "/usr/local/bin/trstctl-sign-approve", "generateKek": true} // #nosec G101 -- fabricated fixture identifiers; the test needs the shape, no value is real (CWE-798)
	f.tcps = []map[string]any{cr}
	srv := httptest.NewServer(f.handler())
	defer srv.Close()
	r := reconcilerForCluster(srv)
	if _, err := r.ReconcileNamespace(context.Background(), "trstctl-system"); err != nil {
		t.Fatalf("reconcile: %v", err)
	}
	for _, want := range []struct{ name, key, component string }{
		{"prod-kek", "kek.bin", "kek"},
		{"prod-signer-auth", "sign-auth.bin", "signer-auth"},
	} {
		obj, ok := f.secrets[want.name]
		if !ok {
			t.Fatalf("Secret %s was not generated (have %v)", want.name, keys(f.secrets))
		}
		if value := secretData(t, obj, want.key); len(value) != 44 { // base64 of 32 bytes
			t.Fatalf("Secret %s key %s = %d base64 characters, want 32 bytes", want.name, want.key, len(value))
		}
		meta := obj["metadata"].(map[string]any)
		labels := meta["labels"].(map[string]any)
		if labels[managedByLabel] != managedByOperator || labels[ownerLabel] != "prod" || labels["app.kubernetes.io/component"] != want.component {
			t.Fatalf("Secret %s labels = %v", want.name, labels)
		}
		if _, owned := meta["ownerReferences"]; owned {
			t.Fatalf("Secret %s carries an owner reference; deleting the control plane would delete it", want.name)
		}
		if !strings.Contains(meta["annotations"].(map[string]any)["trstctl.com/generated-key"].(string), "never rewritten") {
			t.Fatalf("Secret %s does not say it is kept", want.name)
		}
	}
	kek := secretData(t, f.secrets["prod-kek"], "kek.bin")
	created := len(f.createdSecrets)
	if _, err := r.ReconcileNamespace(context.Background(), "trstctl-system"); err != nil {
		t.Fatalf("second reconcile: %v", err)
	}
	if len(f.createdSecrets) != created || secretData(t, f.secrets["prod-kek"], "kek.bin") != kek {
		t.Fatalf("a second pass rewrote a generated Secret: %d creates, KEK changed %v", len(f.createdSecrets)-created,
			secretData(t, f.secrets["prod-kek"], "kek.bin") != kek)
	}

	// Without generateKek the KEK is the operator's to wait for, not to make.
	plain := newFakeCluster()
	plain.tcps = []map[string]any{tcpObjectFullConfig("prod")}
	srv2 := httptest.NewServer(plain.handler())
	defer srv2.Close()
	if _, err := reconcilerForCluster(srv2).ReconcileNamespace(context.Background(), "trstctl-system"); err != nil {
		t.Fatalf("reconcile: %v", err)
	}
	if _, made := plain.secrets["prod-kek"]; made {
		t.Fatal("a KEK was generated without generateKek")
	}
	if _, made := plain.secrets["prod-signer-auth"]; !made {
		t.Fatal("the signer authorization Secret was not generated by default")
	}

	// Named Secrets, or generateAuthSecret false, are never generated.
	named := newFakeCluster()
	no := false
	cr = tcpObjectFullConfig("prod")
	cr["spec"].(map[string]any)["signer"] = map[string]any{"authTokenCommand": "/usr/local/bin/trstctl-sign-approve", "generateKek": true, // #nosec G101 -- fabricated fixture identifiers; the test needs the shape, no value is real (CWE-798)
		"kekSecret": "my-kek", "generateAuthSecret": no}
	named.tcps = []map[string]any{cr}
	srv3 := httptest.NewServer(named.handler())
	defer srv3.Close()
	if _, err := reconcilerForCluster(srv3).ReconcileNamespace(context.Background(), "trstctl-system"); err != nil {
		t.Fatalf("reconcile: %v", err)
	}
	if len(named.createdSecrets) != 0 {
		t.Fatalf("named or opted-out Secrets were generated: %v", keys(named.secrets))
	}
}

func keys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	slices.Sort(out)
	return out
}

// TestOperatorExternalKMSCustodyHELMO1: with spec.externalKMS the signer seals
// its key store through the KMS adapter, as the chart renders it, in both
// topologies: the adapter flags instead of --kek, the adapter's configuration
// Secret mounted with TRSTCTL_KMS_WRAP_CONFIG, no KEK in the signer, while the
// control plane keeps the KEK for secrets. An unusable KMS spec is refused.
func TestOperatorExternalKMSCustodyHELMO1(t *testing.T) {
	kms := map[string]any{"enabled": true, "provider": "awskms", "keyRef": "arn:aws:kms:us-east-1:111111111111:key/abc", "adapterConfigSecret": "kms-config"} // #nosec G101 -- fabricated fixture identifiers; the test needs the shape, no value is real (CWE-798)
	want := []string{"--kms-provider=awskms", "--kms-key-ref=arn:aws:kms:us-east-1:111111111111:key/abc",
		"--kms-wrap-command=/usr/local/bin/trstctl-kms-wrap", "--kms-timeout=10s"}
	checkSigner := func(t *testing.T, signer map[string]any) {
		t.Helper()
		args := containerArgs(signer)
		for _, w := range want {
			if !slices.Contains(args, w) {
				t.Fatalf("signer args %v lack %s", args, w)
			}
		}
		for _, a := range args {
			if strings.HasPrefix(a, "--kek=") {
				t.Fatalf("a KMS-custody signer still names the KEK: %v", args)
			}
		}
		if containerHasMount(signer, "kek", "/etc/trstctl/kek") || !containerHasMount(signer, "kms-wrap", "/etc/trstctl/kms-wrap") {
			t.Fatal("the signer mounts the KEK, or not the adapter's configuration")
		}
		env, _ := normalize(t, signer).(map[string]any)["env"].([]any)
		if envLiteral(env, "TRSTCTL_KMS_WRAP_CONFIG") != "/etc/trstctl/kms-wrap/config.json" {
			t.Fatalf("signer env = %v", env)
		}
	}

	// Sidecar.
	f := newFakeCluster()
	cr := tcpObjectFullConfig("prod")
	cr["spec"].(map[string]any)["externalKMS"] = kms
	f.tcps = []map[string]any{cr}
	srv := httptest.NewServer(f.handler())
	defer srv.Close()
	if _, err := reconcilerForCluster(srv).ReconcileNamespace(context.Background(), "trstctl-system"); err != nil {
		t.Fatalf("reconcile: %v", err)
	}
	created := f.created[0]
	checkSigner(t, containerByName(t, created, "signer"))
	if !hasVolume(created, "kms-wrap") || !hasVolume(created, "kek") {
		t.Fatal("the sidecar pod lacks the adapter's configuration volume, or the control plane's KEK")
	}
	if !containerHasMount(containerByName(t, created, "control-plane"), "kek", "/etc/trstctl/kek") {
		t.Fatal("the control plane lost its KEK for secrets")
	}

	// Isolated signer.
	iso := newFakeCluster()
	cr = tcpObjectFullConfig("prod")
	cr["spec"].(map[string]any)["signerMode"] = "isolated"
	cr["spec"].(map[string]any)["externalKMS"] = kms
	iso.tcps = []map[string]any{cr}
	srv2 := httptest.NewServer(iso.handler())
	defer srv2.Close()
	if _, err := reconcilerForCluster(srv2).ReconcileNamespace(context.Background(), "trstctl-system"); err != nil {
		t.Fatalf("reconcile: %v", err)
	}
	signerDeployment, ok := iso.deployments["prod-signer"]
	if !ok {
		t.Fatalf("no isolated signer Deployment (have %v)", keys(iso.deployments))
	}
	checkSigner(t, containerByName(t, signerDeployment, "signer"))
	if hasVolume(signerDeployment, "kek") || !hasVolume(signerDeployment, "kms-wrap") {
		t.Fatal("the isolated signer pod carries the KEK, or lacks the adapter's configuration")
	}

	// An unusable KMS spec is refused before anything is rendered.
	for name, bad := range map[string]map[string]any{
		"unknown provider": {"enabled": true, "provider": "rot13", "keyRef": "k"},
		"no key":           {"enabled": true, "provider": "gcpkms"},
		"relative command": {"enabled": true, "provider": "azurekv", "keyRef": "k", "wrapCommand": "kms-wrap"},
		"bad timeout":      {"enabled": true, "provider": "pkcs11", "keyRef": "k", "timeout": "soon"},
	} {
		t.Run(name, func(t *testing.T) {
			refused := newFakeCluster()
			cr := tcpObjectFullConfig("prod")
			cr["spec"].(map[string]any)["externalKMS"] = bad
			refused.tcps = []map[string]any{cr}
			srv := httptest.NewServer(refused.handler())
			defer srv.Close()
			_, _ = reconcilerForCluster(srv).ReconcileNamespace(context.Background(), "trstctl-system")
			if len(refused.created) != 0 || !strings.Contains(refused.statusSet["prod"]["message"].(string), "externalKMS") {
				t.Fatalf("an unusable KMS spec rendered %d Deployments; status %v", len(refused.created), refused.statusSet["prod"])
			}
		})
	}
}

// TestOperatorRendersTheDisruptionBudgetAndServiceMonitorHELMO1: a
// multi-replica control plane gets a PodDisruptionBudget (minAvailable 1) over
// its own pods, a single replica none, and a budget that would block every
// drain is refused; turning it off removes it. A ServiceMonitor scrapes the
// control plane's Service over HTTPS when the Prometheus Operator's API is
// served, is refused with the reason when it is not, and is removed when the
// spec drops it.
func TestOperatorRendersTheDisruptionBudgetAndServiceMonitorHELMO1(t *testing.T) {
	ctx := context.Background()
	f := newFakeCluster()
	f.serviceMonitorAPI = true
	cr := tcpObject("prod", 2, "ghcr.io/ctlplne/trstctl:v9")
	cr["spec"].(map[string]any)["serviceMonitor"] = map[string]any{"enabled": true, "labels": map[string]any{"release": "prom"}}
	f.tcps = []map[string]any{cr}
	srv := httptest.NewServer(f.handler())
	defer srv.Close()
	r := reconcilerForCluster(srv)
	if _, err := r.ReconcileNamespace(ctx, "trstctl-system"); err != nil {
		t.Fatalf("reconcile: %v", err)
	}
	pdb, ok := f.objects["poddisruptionbudgets/prod-control-plane"]
	if !ok {
		t.Fatalf("no PodDisruptionBudget for a two-replica control plane (have %v)", keys(f.objects))
	}
	p := normalize(t, pdb)
	if dig(t, p, "spec", "minAvailable") != float64(1) || dig(t, p, "spec", "selector", "matchLabels", controlPlaneLabel) != "prod" ||
		dig(t, p, "metadata", "ownerReferences", 0, "uid") != "uid-prod" {
		t.Fatalf("PodDisruptionBudget = %v", p)
	}
	sm, ok := f.objects["servicemonitors/prod-control-plane"]
	if !ok {
		t.Fatalf("no ServiceMonitor (have %v)", keys(f.objects))
	}
	m := normalize(t, sm)
	if dig(t, m, "spec", "endpoints", 0, "port") != "https" || dig(t, m, "spec", "endpoints", 0, "scheme") != "https" ||
		dig(t, m, "spec", "endpoints", 0, "path") != "/metrics" || dig(t, m, "spec", "endpoints", 0, "interval") != "30s" ||
		dig(t, m, "metadata", "labels", "release") != "prom" ||
		dig(t, m, "spec", "selector", "matchLabels", "app.kubernetes.io/component") != "control-plane" {
		t.Fatalf("ServiceMonitor = %v", m)
	}

	// The spec drops both: both are removed.
	no := false
	cr["spec"].(map[string]any)["podDisruptionBudget"] = map[string]any{"enabled": no}
	cr["spec"].(map[string]any)["serviceMonitor"] = map[string]any{"enabled": false}
	if _, err := r.ReconcileNamespace(ctx, "trstctl-system"); err != nil {
		t.Fatalf("reconcile: %v", err)
	}
	for _, gone := range []string{"poddisruptionbudgets/prod-control-plane", "servicemonitors/prod-control-plane"} {
		if _, still := f.objects[gone]; still || !slices.Contains(f.deletedObjects, gone) {
			t.Fatalf("%s was not removed once the spec dropped it", gone)
		}
	}

	// A single replica gets no budget, and one that would block every drain is refused.
	single := newFakeCluster()
	single.tcps = []map[string]any{tcpObject("solo", 1, "ghcr.io/ctlplne/trstctl:v9")}
	srv2 := httptest.NewServer(single.handler())
	defer srv2.Close()
	if _, err := reconcilerForCluster(srv2).ReconcileNamespace(ctx, "trstctl-system"); err != nil {
		t.Fatalf("reconcile: %v", err)
	}
	if _, made := single.objects["poddisruptionbudgets/solo-control-plane"]; made {
		t.Fatal("a single-replica control plane got a disruption budget that would block its node's drain")
	}
	blocking := newFakeCluster()
	cr = tcpObject("solo", 1, "ghcr.io/ctlplne/trstctl:v9")
	yes := true
	cr["spec"].(map[string]any)["podDisruptionBudget"] = map[string]any{"enabled": yes}
	blocking.tcps = []map[string]any{cr}
	srv3 := httptest.NewServer(blocking.handler())
	defer srv3.Close()
	_, _ = reconcilerForCluster(srv3).ReconcileNamespace(ctx, "trstctl-system")
	if len(blocking.created) != 0 || !strings.Contains(blocking.statusSet["solo"]["message"].(string), "block every voluntary disruption") {
		t.Fatalf("a budget blocking every drain = %d Deployments, status %v", len(blocking.created), blocking.statusSet["solo"])
	}

	// No Prometheus Operator API: the ServiceMonitor is refused with the reason.
	bare := newFakeCluster()
	cr = tcpObject("prod", 2, "ghcr.io/ctlplne/trstctl:v9")
	cr["spec"].(map[string]any)["serviceMonitor"] = map[string]any{"enabled": true}
	bare.tcps = []map[string]any{cr}
	srv4 := httptest.NewServer(bare.handler())
	defer srv4.Close()
	_, _ = reconcilerForCluster(srv4).ReconcileNamespace(ctx, "trstctl-system")
	if !strings.Contains(bare.statusSet["prod"]["message"].(string), "monitoring.coreos.com/v1") {
		t.Fatalf("a ServiceMonitor without the Prometheus Operator API = status %v", bare.statusSet["prod"])
	}
}
