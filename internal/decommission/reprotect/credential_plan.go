package reprotect

import (
	"context"
	"encoding/json"
	"fmt"
	"strings"

	"trstctl.com/trstctl/internal/crypto"
	"trstctl.com/trstctl/internal/decommission/depstate"
	"trstctl.com/trstctl/internal/events"
	corestore "trstctl.com/trstctl/internal/store"
)

// TypeCredentialPlan is an immutable, public-only command binding. No private
// subject key or management credential may enter this event.
const TypeCredentialPlan = "reprotection.credential_plan_recorded"

// CredentialPlan pins the predecessor and the exact execution route before a
// worker may reissue a credential. The CSR is generated by the bound host from
// its retained key; the signer must compare that CSR with the predecessor SPKI
// and names before it signs. The target revision prevents a later route edit
// from silently moving the operation to another host.
type CredentialPlan struct {
	Job                    Job    `json:"job"`
	SuccessorAuthorityID   string `json:"successor_authority_id"`
	PredecessorFingerprint string `json:"predecessor_fingerprint"`
	PredecessorSPKISHA256  string `json:"predecessor_spki_sha256"`
	TargetID               string `json:"target_id"`
	TargetRevisionID       string `json:"target_revision_id"`
	RequiredAgentID        string `json:"required_agent_id"`
	Connector              string `json:"connector"`
	VerifyAddress          string `json:"verify_address"`
	VerifyServerName       string `json:"verify_server_name"`
	TTLSeconds             int64  `json:"ttl_seconds"`
}

// CredentialPlanLedger uses the indexed event ID as the first-writer key. It
// never scans the event log on the request or agent path.
type CredentialPlanLedger struct {
	log   *events.Log
	store *corestore.Store
}

func NewCredentialPlanLedger(log *events.Log, store *corestore.Store) *CredentialPlanLedger {
	return &CredentialPlanLedger{log: log, store: store}
}

func (l *CredentialPlanLedger) Record(ctx context.Context, plan CredentialPlan) (bool, error) {
	if err := validateCredentialPlan(plan); err != nil {
		return false, err
	}
	if l == nil {
		return false, ErrExecutorUnavailable
	}
	raw, err := json.Marshal(plan)
	if err != nil {
		return false, fmt.Errorf("reprotect: encode credential plan: %w", err)
	}
	return (eventSink{log: l.log, store: l.store}).appendBoundEventOnce(ctx,
		"vdec-credential-plan", planIdentity(plan.Job.TenantID, plan.Job.ID), events.Event{
			Type: TypeCredentialPlan, TenantID: plan.Job.TenantID,
			SchemaVersion: depstate.SchemaV1, Data: raw,
		})
}

func (l *CredentialPlanLedger) Load(ctx context.Context, tenantID, jobID string) (CredentialPlan, bool, error) {
	if l == nil || l.log == nil || l.store == nil {
		return CredentialPlan{}, false, ErrExecutorUnavailable
	}
	if strings.TrimSpace(tenantID) == "" || strings.TrimSpace(jobID) == "" {
		return CredentialPlan{}, false, fmt.Errorf("%w: tenant and job are required", ErrInvalidState)
	}
	ev, found, err := l.log.EventByID(ctx, planEventID(tenantID, jobID))
	if err != nil || !found {
		return CredentialPlan{}, found, err
	}
	if ev.TenantID != tenantID || ev.Type != TypeCredentialPlan || ev.SchemaVersion != depstate.SchemaV1 {
		return CredentialPlan{}, false, ErrCompletionConflict
	}
	var plan CredentialPlan
	if err := json.Unmarshal(ev.Data, &plan); err != nil {
		return CredentialPlan{}, false, fmt.Errorf("reprotect: decode credential plan: %w", err)
	}
	if plan.Job.TenantID != tenantID || plan.Job.ID != jobID {
		return CredentialPlan{}, false, ErrCompletionConflict
	}
	if err := validateCredentialPlan(plan); err != nil {
		return CredentialPlan{}, false, err
	}
	return plan, true, nil
}

func planIdentity(tenantID, jobID string) string { return tenantID + "\x1f" + jobID }

func planEventID(tenantID, jobID string) string {
	return "vdec-credential-plan:" + crypto.SHA256Hex([]byte(planIdentity(tenantID, jobID)))
}

func validateCredentialPlan(plan CredentialPlan) error {
	if err := validateJob(plan.Job); err != nil {
		return err
	}
	if plan.Job.Kind != JobKindReIssue || plan.Job.Dependent.Class != depstate.DependentCredential {
		return fmt.Errorf("%w: credential plan requires a re-issue job", ErrInvalidState)
	}
	if plan.SuccessorAuthorityID == "" || plan.SuccessorAuthorityID == plan.Job.KeyID ||
		plan.PredecessorFingerprint == "" || plan.PredecessorSPKISHA256 == "" ||
		plan.TargetID == "" || plan.TargetRevisionID == "" || plan.RequiredAgentID == "" ||
		plan.Connector == "" || plan.VerifyAddress == "" || plan.VerifyServerName == "" || plan.TTLSeconds <= 0 {
		return fmt.Errorf("%w: credential plan lacks bound successor, predecessor, route, verification or TTL", ErrInvalidState)
	}
	return nil
}
