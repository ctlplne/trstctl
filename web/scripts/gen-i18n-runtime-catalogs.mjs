#!/usr/bin/env node
// Generate the English production catalog from typed messages.ts descriptors.
// The runtime contains ordered IDs and values, without review descriptions.
// Usage: node scripts/gen-i18n-runtime-catalogs.mjs [--check]
// Fail closed on malformed source or stale output; extraction remains separate.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(scriptDirectory, "..");
const i18nRoot = path.resolve(webRoot, "src", "i18n");
const check = process.argv.includes("--check");

const locales = ["en-US"];

function unwrap(expression) {
  let current = expression;
  while (ts.isAsExpression(current) || ts.isSatisfiesExpression(current) || ts.isParenthesizedExpression(current)) {
    current = current.expression;
  }
  return current;
}

function objectLiteral(file, variableName) {
  const sourceText = readFileSync(file, "utf8");
  const source = ts.createSourceFile(file, sourceText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  for (const statement of source.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (!ts.isIdentifier(declaration.name) || declaration.name.text !== variableName || !declaration.initializer) continue;
      const initializer = unwrap(declaration.initializer);
      if (!ts.isObjectLiteralExpression(initializer)) {
        throw new Error(`${file}: ${variableName} must be an object literal`);
      }
      return initializer;
    }
  }
  throw new Error(`${file}: cannot find ${variableName}`);
}

function literalEntries(file, variableName, valueSelector) {
  const object = objectLiteral(file, variableName);
  const entries = new Map();
  for (const property of object.properties) {
    if (!ts.isPropertyAssignment(property)) {
      throw new Error(`${file}:${property.getStart()}: catalog entries must be property assignments`);
    }
    const name = property.name;
    if (!ts.isStringLiteralLike(name)) {
      throw new Error(`${file}:${name.getStart()}: catalog keys must be string literals`);
    }
    if (entries.has(name.text)) throw new Error(`${file}: duplicate catalog key ${JSON.stringify(name.text)}`);
    const value = valueSelector(property.initializer, name.text);
    entries.set(name.text, value);
  }
  return entries;
}

const messagesFile = path.resolve(i18nRoot, "messages.ts");
const messages = literalEntries(messagesFile, "messages", (initializer, key) => {
  const descriptor = unwrap(initializer);
  if (!ts.isObjectLiteralExpression(descriptor)) {
    throw new Error(`${messagesFile}: descriptor for ${JSON.stringify(key)} must be an object literal`);
  }
  const defaultProperty = descriptor.properties.find(
    (property) => ts.isPropertyAssignment(property) && ts.isIdentifier(property.name) && property.name.text === "defaultMessage",
  );
  if (!defaultProperty || !ts.isPropertyAssignment(defaultProperty)) {
    throw new Error(`${messagesFile}: descriptor for ${JSON.stringify(key)} has no defaultMessage`);
  }
  const value = unwrap(defaultProperty.initializer);
  if (!ts.isStringLiteralLike(value)) {
    throw new Error(`${messagesFile}: defaultMessage for ${JSON.stringify(key)} must be a string literal`);
  }
  return value.text;
});
const orderedKeys = [...messages.keys()];

function generateEnglishRuntime() {
  const keys = orderedKeys.map((key) => `  ${JSON.stringify(key)},`).join("\n");
  const values = orderedKeys.map((key) => `  ${JSON.stringify(messages.get(key))},`).join("\n");
  return [
    "// Code generated by web/scripts/gen-i18n-runtime-catalogs.mjs.",
    "// DO NOT EDIT. Edit messages.ts and regenerate.",
    "",
    "// Production needs message IDs and values, but not translator descriptions.",
    "// prettier-ignore",
    "export const orderedMessageKeys = [",
    keys,
    "] as const;",
    "",
    "// One value for each ID above. The generator enforces exact ordering.",
    "// prettier-ignore",
    "export const defaultMessageValues = [",
    values,
    "] as const;",
    "",
  ].join("\n");
}

let stale = false;
const outputs = locales.map((locale) => ({
  outputFile: path.resolve(i18nRoot, `catalog.${locale}.runtime.gen.ts`),
  generated: generateEnglishRuntime(),
}));

for (const { outputFile, generated } of outputs) {
  if (check) {
    let current = "";
    try {
      current = readFileSync(outputFile, "utf8");
    } catch {
      // Report the same actionable stale error for missing and changed output.
    }
    if (current !== generated) {
      console.error(`${path.relative(webRoot, outputFile)} is stale; run npm run gen:i18n-runtime`);
      stale = true;
    }
  } else {
    writeFileSync(outputFile, generated);
    console.log(`generated ${path.relative(webRoot, outputFile)}`);
  }
}

if (stale) process.exitCode = 1;
